// The poster's DROP A and TRACK as outlines (app/poster-words.ts): drawn as SVG they scale with
// CSS alone, so they're there at first paint with no font to wait for and nothing to refit.
// Each viewBox is the ink edge to edge, cap top to baseline, as FitText trims it.
// Run: pnpm tsx scripts/build-poster-words.ts
import { readFileSync, writeFileSync } from "node:fs";
import { parse } from "opentype.js";

const buf = readFileSync("app/fonts/Shapiro-95-Super-Extd.otf");
const font = parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const SIZE = 1000;
const cap = Math.round(-font.getPath("H", 0, 0, SIZE).getBoundingBox().y1);

function word(text: string, letterSpacing: number) {
  const path = font.getPath(text, 0, 0, SIZE, { kerning: true, letterSpacing } as object);
  const { x1, x2 } = path.getBoundingBox();
  return { d: path.toPathData(1), x: Math.floor(x1), w: Math.ceil(x2) - Math.floor(x1), cap };
}

const out = `// Generated by scripts/build-poster-words.ts — don't edit.
export const DROP_A = ${JSON.stringify(word("DROP A", -0.02))};
export const TRACK = ${JSON.stringify(word("TRACK", 0))};
`;
writeFileSync("app/poster-words.ts", out);
console.log("app/poster-words.ts", out.length, "bytes");
